    const normalize = (text) => text.replace(/\s+/g, " ").trim();
    const translations = new Map();
    for (const [en, id] of entries) {
        const pair = { en, id };
        translations.set(normalize(en), pair);
        translations.set(normalize(id), pair);
    }
    let language = "en";
    try {
        if (localStorage.getItem("language") === "id") language = "id";
    } catch {}

    function t(text, values = {}) {
        let result = translations.get(normalize(text))?.[language] ?? text;
        if (language === "en" && values.count === 1) {
            result = result.replace("{count} projects", "{count} project").replace("{count} previews", "{count} preview");
        }
        return result.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
    }

    function translatePage() {
        const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
        while (walker.nextNode()) {
            const node = walker.currentNode;
            if (node.parentElement.closest("script, style")) continue;
            const pair = translations.get(normalize(node.nodeValue));
            if (pair) {
                const leading = node.nodeValue.match(/^\s*/)[0];
                const trailing = node.nodeValue.match(/\s*$/)[0];
                node.nodeValue = leading + pair[language] + trailing;
            }
        }
        for (const element of document.querySelectorAll("[aria-label], [title], [placeholder], [alt], meta[content]")) {
            for (const attribute of ["aria-label", "title", "placeholder", "alt", "content"]) {
                if (!element.hasAttribute(attribute)) continue;
                const original = element.getAttribute(attribute);
                const pair = translations.get(normalize(original));
                if (pair) element.setAttribute(attribute, pair[language]);
            }
        }
    }

    function applyLanguage(nextLanguage, persist = false) {
        if (nextLanguage !== "en" && nextLanguage !== "id") return;
        language = nextLanguage;
        document.documentElement.lang = language;
        translatePage();
        document.querySelectorAll("[data-language]").forEach((button) => {
            button.setAttribute("aria-pressed", String(button.dataset.language === language));
        });
        if (persist) {
            try { localStorage.setItem("language", language); } catch {}
        }
        document.dispatchEvent(new CustomEvent("languagechange", { detail: { language } }));
    }

    window.siteI18n = {
        t,
        variants(text) {
            const pair = translations.get(normalize(text));
            return pair ? [pair.en, pair.id] : [text];
        },
        get language() { return language; },
    };
    document.querySelectorAll("[data-language]").forEach((button) => {
        button.addEventListener("click", () => applyLanguage(button.dataset.language, true));
    });
    applyLanguage(language);
    document.querySelector(".site-preferences").hidden = false;
